export function getProjectImage(
  projectId: string,
  _type: string = 'Website',
  kind: 'cover' | 'hero' | 'mobile' | 'tablet' | 'gallery' = 'cover'
): string {
  const meta = defaultProjectImages[projectId] || DAEWOO_GENERAL;

  if (kind === 'gallery') return meta.gallery[0] || meta.cover;
  if (kind === 'tablet') return meta.tablet || meta.hero || meta.cover;
  if (kind === 'mobile') return meta.mobile || meta.cover;
  if (kind === 'hero') return meta.hero || meta.cover;
  return meta.cover;
}
